import type { InvoiceTrigger } from '@prisma/client';

/** One line telling staff when an order's GST invoice will be made. */
export function triggerNote(trigger: InvoiceTrigger): string {
  if (trigger === 'ON_CONFIRM') return 'The invoice is generated when the order is confirmed. Change this in Settings › Orders & invoicing.';
  if (trigger === 'MANUAL') return 'Invoices are generated by hand from each order. Change this in Settings › Orders & invoicing.';
  return 'The invoice is generated when the order is dispatched, so it travels with the goods. Change this in Settings › Orders & invoicing.';
}
